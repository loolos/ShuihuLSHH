/** '@wusong' → 包职业号；'@12' → 原版职业号；别的原样（旁人称呼） */
function speaker(rt: PackRuntime, who: string): Speaker {
  if (!who.startsWith('@')) return who;
  const k = who.slice(1);
  if (/^\d+$/.test(k)) return Number(k);
  const id = rt.classIds.get(k);
  if (id === undefined) throw new Error(`酒馆说书：没有职业 ${k}`);
  return id;
}

const cls = (rt: PackRuntime, k: string) => speaker(rt, k.startsWith('@') ? k : `@${k}`) as number;

function line(rt: PackRuntime, l: RawLine): TaleLine {
  return { who: speaker(rt, l.who), text: l.text, ...(l.need ? { need: l.need.map((n) => cls(rt, n)) } : {}) };
}

/** 这个续篇城镇（按下一关）的传闻和说书；职业名换成这个包的职业号 */
export function insertTavern(rt: PackRuntime, next: string): { rumors: string[]; tale: Tale } | undefined {
  const t = TAVERNS[next];
  if (!t) return undefined;
  const r = t.tale;
  const opt = (o: RawOption): TaleOption => ({
    label: o.label,
    note: o.note,
    lines: o.lines.map((l) => line(rt, l)),
    ...(o.gift ? { gift: { item: o.gift.item, lines: o.gift.lines.map((l) => line(rt, l)), ...(o.gift.full ? { full: o.gift.full.map((l) => line(rt, l)) } : {}) } } : {}),
  });
  return {
    rumors: t.rumors,
    tale: {
      id: r.id,
      town: 0,
      title: r.title,
      hero: cls(rt, r.hero),
      pages: r.pages,
      absent: r.absent.map((l) => line(rt, l)),
      present: r.present.map((l) => line(rt, l)),
      choice: { title: r.choice.title, text: r.choice.text, options: r.choice.options.map(opt) },
    },
  };
}
