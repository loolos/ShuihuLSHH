/**
 * 把显示用的名字拆成 [绰号, 名字]。
 * 名字本身已经带绰号（关卡里写的「小李广花荣」）也拆开，避免显示成「小李广 小李广花荣」。
 * extra：运行时补充的绰号（主角名 → EXE 绰号）。没有绰号时返回 ['', name]。
 */
export function splitNickname(name: string, extra?: Readonly<Record<string, string>>): [string, string] {
  const own = extra?.[name] || NICKNAMES[name];
  if (own) return [own, name];
  for (const [bare, nick] of Object.entries(NICKNAMES)) if (nick && name === nick + bare) return [nick, bare];
  return ['', name];
}

